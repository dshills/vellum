// Package ui describes retained, keyed UI records using ordinary Go values.
package ui

import (
	"fmt"
	"strings"

	"github.com/dshills/vellum/canvas"
	"github.com/dshills/vellum/editor"
	"github.com/dshills/vellum/placement"
	"github.com/dshills/vellum/virtual"
)

type Kind string

const (
	Column    Kind = "column"
	Row       Kind = "row"
	Label     Kind = "label"
	Button    Kind = "button"
	Icon      Kind = "icon"
	Image     Kind = "image"
	Extension Kind = "extension"
)

// Node IDs are stable within one window. The menu: prefix is reserved for
// private action popup items. The grid: prefix is reserved for
// generated grid cell/row/header identities. The tree: prefix similarly reserves
// managed outline row/disclosure/page targets. split: reserves native divider
// targets. disclosure: reserves native section-heading targets. These prefixes
// are refused in descriptions. tab-close: reserves private document-tab close targets.
// A View returns a fresh description;
// callbacks run on the application owner. Custom holds driver-specific content.
type Node struct {
	ID string
	// Theme replaces inherited styling for this subtree. Nil inherits. Drivers
	// snapshot maps at accepted View boundaries; never mutate them concurrently.
	Theme *Theme
	Kind  Kind
	Text  string
	// Placeholder is a non-value hint on TextField; Accessibility.Name remains its label.
	Placeholder string
	// Secure protects TextField visual/native accessibility exposure even when
	// Reveal is explicitly requested. Reveal belongs only on a Secure field.
	Secure, Reveal bool
	// ShortcutRecorder marks the managed button produced by its View method.
	ShortcutRecorder *ShortcutRecorder
	// ToolbarReorder marks a managed drag grip generated by ToolbarCustomizer.
	ToolbarReorder *ToolbarReorderHandle
	// Icon is bundled artwork for Icon/Button/ToggleButton. Text is alternate
	// text for an Icon. Icon-only actions require Accessibility.Name.
	Icon Symbol
	// IconImage is immutable full-color artwork for Button/MenuButton. It is
	// mutually exclusive with Icon and scales into the button’s icon slot.
	// Icon-only actions require Accessibility.Name; artwork adds no focus stop.
	IconImage *canvas.TiledImage
	// IconPlacement changes Button content layout. Empty/IconLeading keeps the
	// ordinary inline layout; IconAboveText centers artwork above its caption.
	IconPlacement ButtonIconPlacement
	// Appearance changes Button presentation without changing its action.
	Appearance ButtonAppearance
	// Image holds immutable shared pixels for an Image node. Fit changes
	// painting within its content box; Text/Accessibility.Name are alternate text.
	Image *canvas.TiledImage
	Fit   ImageFit
	// Editor owns multiline document state and history; one live native binding is supported.
	Editor *editor.Model
	// Grid is caller-owned. One live managed binding per Grid is supported.
	Grid       *virtual.Grid
	GridChange func(GridEvent)
	// GridCommit requests application validation and candidate admission after
	// the driver has settled the originating native cell editor. It runs on owner.
	GridCommit func(GridEditEvent)
	// Tree owns an indexed outline. One live managed binding per Outline is supported.
	Tree           *virtual.Outline
	TreeChange     func(TreeEvent)
	TreeDisclosure func(TreeDisclosureEvent)
	// TabInserts makes Tab insert a literal tab in MultilineText; otherwise Tab moves focus.
	TabInserts bool
	// SoftWrap wraps visual lines without changing document bytes.
	SoftWrap            bool
	Disabled            bool
	Grow                bool
	MinWidth, MinHeight float32
	Activate            func()
	FileDrop            func(FileDropEvent) bool
	Children            []Node
	ContextMenu         *ContextMenu
	Custom              any
	// Canvas2D uses logical canvas units and the existing canvas navigation model.
	Canvas *canvas.Scene
	// CanvasObjects optionally exposes named scene objects to assistive technology.
	CanvasObjects   []CanvasObject
	CanvasGrid      float32           // optional world-space grid spacing; zero hides it
	PlacementSource *placement.Source // focusable palette Button; Activate supplies keyboard placement
	PlacementTarget *placement.Target // optional Canvas2D acceptance endpoint
	// CalendarCell is immutable focus metadata emitted by Calendar.View.
	CalendarCell *CalendarCell
	AngleDial    *AngleDialInput
	DocumentList *DocumentListLayout
	Outline      *OutlineViewLayout
	ColumnResize *ColumnResizeHandle
	// SplitButtonLayout marks the two segments produced by SplitButton.View.
	// It is a detached presentation hint; callbacks remain ordinary child actions.
	SplitButtonLayout bool
	Style             Style
	Checked           bool
	Number            float32
	Numeric           Numeric
	// NumberButtons optionally selects compact up/down arrows on NumberField.
	NumberButtons NumberFieldButtons
	// Orientation applies to display/choice/toolbar/split controls; RadioGroup defaults vertical.
	// ToolbarOverflow is set by WithToolbarOverflow for horizontal action bars.
	ToolbarOverflow bool
	Orientation     Orientation
	Options         []Option
	// Multiple/SelectedIDs/SelectionChange belong only on ListBox.
	Collection      *CollectionLayout
	Multiple        bool
	SelectedIDs     []string
	SelectionChange func(ListSelectionEvent)
	MenuAnchorID    string // optional same-window managed anchor for MenuButton
	SelectedID      string
	// TabsHideHeader retains a page stack controlled by external navigation.
	TabsHideHeader bool
	TabClose       func(TabCloseEvent)
	Change         func(ChangeEvent)
	Accessibility  Accessibility
	Focus          FocusRequest
	// PopoverAnchor makes a Dialog an anchored panel; prefer Popover.View.
	// Sheet requests a nonresizable window-modal card with explicit actions.
	Sheet                                bool
	DialogDefaultID, DialogReturnFocusID string
	PopoverAnchor                        string
	Open                                 bool
	Dismiss                              func()
}

func Validate(root Node) error {
	seen := map[string]bool{}
	models := map[*editor.Model]bool{}
	grids := map[*virtual.Grid]bool{}
	trees := map[*virtual.Outline]bool{}
	canvases := map[*canvas.Scene]bool{}
	sources := map[*placement.Source]bool{}
	targets := map[*placement.Target]bool{}
	var walk func(Node, int, Theme) error
	walk = func(n Node, depth int, theme Theme) error {
		if n.Theme != nil {
			theme = *n.Theme
			if err := theme.Validate(); err != nil {
				return err
			}
		}
		if depth >= 128 {
			return fmt.Errorf("ui: hierarchy exceeds 128 levels")
		}
		if n.ID == "" || seen[n.ID] {
			return fmt.Errorf("ui: empty or duplicate ID %q", n.ID)
		}
		if strings.HasPrefix(n.ID, "canvas-object:") {
			return fmt.Errorf("ui: ID %q uses reserved canvas-object: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "grid:") {
			return fmt.Errorf("ui: ID %q uses reserved grid: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "tree:") {
			return fmt.Errorf("ui: ID %q uses reserved tree: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "split:") {
			return fmt.Errorf("ui: ID %q uses reserved split: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "disclosure:") {
			return fmt.Errorf("ui: ID %q uses reserved disclosure: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "menu:") {
			return fmt.Errorf("ui: ID %q uses reserved menu: prefix", n.ID)
		}
		if strings.HasPrefix(n.ID, "tab-close:") {
			return fmt.Errorf("ui: ID %q uses reserved tab-close: prefix", n.ID)
		}
		seen[n.ID] = true
		if n.Canvas != nil {
			if canvases[n.Canvas] {
				return fmt.Errorf("ui: canvas model has multiple bindings")
			}
			canvases[n.Canvas] = true
		}
		if n.PlacementSource != nil {
			if sources[n.PlacementSource] {
				return fmt.Errorf("ui: placement source has multiple bindings")
			}
			sources[n.PlacementSource] = true
		}
		if n.PlacementTarget != nil {
			if targets[n.PlacementTarget] {
				return fmt.Errorf("ui: placement target has multiple bindings")
			}
			targets[n.PlacementTarget] = true
		}
		if n.Kind == MultilineText {
			if models[n.Editor] {
				return fmt.Errorf("ui: editor model has multiple bindings")
			}
			models[n.Editor] = true
		}
		if n.Kind == DataGrid {
			if grids[n.Grid] {
				return fmt.Errorf("ui: grid model has multiple bindings")
			}
			grids[n.Grid] = true
		}
		if n.Kind == DataTree {
			if trees[n.Tree] {
				return fmt.Errorf("ui: outline model has multiple bindings")
			}
			trees[n.Tree] = true
		}
		if depth > 0 && n.Focus.ID != "" {
			return fmt.Errorf("ui: focus requests belong on the root")
		}
		if err := ValidateControl(n); err != nil {
			return err
		}
		if _, err := ResolveStyle(n, theme); err != nil {
			return err
		}
		switch n.Kind {
		case Column, Row, Tabs, Scroll, Dialog, Toolbar, StatusBar, FormGroup, SplitPane, Disclosure:
		case Label, Button, Icon, Image, Extension, Canvas2D, Checkbox, Switch, ToggleButton, ProgressBar, ProgressRing, ProgressGauge, Separator, ToolbarSpace, ToolbarFlexibleSpace, MenuButton, Selector, ListBox, RadioGroup, SegmentedControl, Slider, NumberField, TextField, MultilineText, DataGrid, DataTree:
			if len(n.Children) != 0 {
				return fmt.Errorf("ui: leaf %q has children", n.ID)
			}
		default:
			return fmt.Errorf("ui: unknown kind %q", n.Kind)
		}
		for _, c := range n.Children {
			if err := walk(c, depth+1, theme); err != nil {
				return err
			}
		}
		return nil
	}
	if err := walk(root, 0, Theme{}); err != nil {
		return err
	}
	return nil
}
